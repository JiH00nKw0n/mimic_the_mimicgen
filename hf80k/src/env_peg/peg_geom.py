"""핀 자세 계산 중 시뮬레이터가 없어도 돌릴 수 있는 부분만 모은 모듈.

여기에 두는 이유는 검사 때문이다. peg_mdp는 불러오는 순간 Isaac Lab을 요구해서
노트북에서는 돌지 않는다. 쿼터니언 순서를 잘못 잡으면 생성이 통째로 무너지므로,
그 부분만은 시뮬레이터 없이도 검사할 수 있어야 한다.
"""
from __future__ import annotations

import torch


def upright_z_from_quat(quat) -> "torch.Tensor":
    """물체의 몸통 z축이 월드 z축과 얼마나 같은 방향인지를 -1에서 1 사이 값으로 돌려준다.

    1이면 똑바로 서 있고, 0이면 옆으로 누워 있고, -1이면 거꾸로 서 있다.

    쿼터니언 순서는 XYZW다. 이 컨테이너의 ``.data.root_quat_w``와
    ``isaaclab.utils.math``의 회전 함수가 모두 XYZW를 쓴다는 것을 두 가지로 확인했다.
    첫째로 컨테이너 안에서 ``quat_from_matrix(단위행렬)``이 ``(0,0,0,1)``을 돌려주었다.
    둘째로 사람 시연 파일의 ``initial_state``에 기록된 로봇 받침 자세가 ``(0,0,1,0)``인데,
    받침이 180도 돌아가 있다는 사실과 맞으려면 XYZW여야 한다.

    식은 회전행렬 (2,2) 성분을 쿼터니언으로 직접 쓴 것이라 라이브러리를 거치지 않는다.
    XYZW에서 그 성분은 ``1 - 2(x^2 + y^2)``이고, x가 0번 자리, y가 1번 자리다.
    """
    return 1.0 - 2.0 * (quat[..., 0] ** 2 + quat[..., 1] ** 2)
